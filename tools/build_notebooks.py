"""Convert each R/0x_*.R script into an R-kernel Jupyter notebook (notebooks/).
The header comment block (step / rationale / interpretation table) becomes a markdown cell;
each '# ---- n. Title ----' section becomes a markdown heading + code cell."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parents[1]
meta = {"kernelspec": {"display_name": "R", "language": "R", "name": "ir"},
        "language_info": {"name": "R", "file_extension": ".r", "mimetype": "text/x-r-source"}}
def md(t): return {"cell_type": "markdown", "metadata": {}, "source": t}
def code(t): return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": t}
def header_to_md(lines):
    body = [l[2:] if l.startswith("# ") else l.lstrip("#") for l in lines if not re.match(r"^# [=-]{10,}", l)]
    out, table = [], False
    for l in body:
        if l.startswith("|"):
            table = True; out.append(l)
        else:
            if table: out.append(""); table = False
            out.append(l)
    return "\n".join(out)
for src in sorted((root / "R").glob("0[1-8]_*.R")):
    lines = src.read_text().split("\n")
    seps = [i for i, l in enumerate(lines) if l.startswith("# =====")]
    head = lines[:seps[1] + 1]; rest = lines[seps[1] + 1:]
    title = src.stem
    cells = [md(f"# {title}\n\n*Notebook version of `R/{src.name}` (generated by `tools/build_notebooks.py`). "
                "Run from the `notebooks/` folder; paths resolve to the repo root automatically. All data are synthetic.*\n\n"
                + header_to_md(head[1:-1]))]
    chunk, heading = [], "Setup"
    def flush():
        txt = "\n".join(chunk).strip("\n")
        if txt.strip():
            cells.append(md(f"## {heading}")); cells.append(code(txt))
    for l in rest:
        m = re.match(r"^# ---- (.*?) -{3,}\s*$", l)
        if m:
            flush(); chunk, heading = [], m.group(1)
        else:
            chunk.append(l)
    flush()
    nb = {"cells": cells, "metadata": meta, "nbformat": 4, "nbformat_minor": 5}
    (root / "notebooks" / f"{title}.ipynb").write_text(json.dumps(nb, indent=1))
    print("wrote notebooks/%s.ipynb (%d cells)" % (title, len(cells)))
